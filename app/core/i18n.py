from __future__ import annotations

import logging
from collections.abc import Callable

logger = logging.getLogger(__name__)


class I18N:
    SUPPORTED = {"zh", "ja", "en"}

    def __init__(self, language: str = "zh") -> None:
        self._language = language if language in self.SUPPORTED else "zh"
        self._listeners: list[Callable[[], None]] = []
        self._validate_message_maps()

    def subscribe(self, callback: Callable[[], None]) -> None:
        self._listeners.append(callback)

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> None:
        if language not in self.SUPPORTED or language == self._language:
            return
        self._language = language
        for cb in self._listeners:
            cb()

    def t(self, key: str) -> str:
        lang_map = MESSAGES.get(self._language, MESSAGES["en"])
        return lang_map.get(key, MESSAGES["en"].get(key, key))

    def _validate_message_maps(self) -> None:
        base_keys = set(MESSAGES["en"].keys())
        for lang in self.SUPPORTED:
            missing = sorted(base_keys - set(MESSAGES.get(lang, {}).keys()))
            if missing:
                logger.warning("i18n missing keys for %s: %s", lang, ", ".join(missing))


